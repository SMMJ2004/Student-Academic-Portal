-- ----------------------------------------------------------------------------
-- 1. STUDENT_DETAILS (Report Page 7)
-- ----------------------------------------------------------------------------
CREATE TABLE STUDENT_DETAILS
 (
 STUDENT_ID VARCHAR2 (30) NOT NULL ,
 STUDENT_NAME VARCHAR2 (100 CHAR) NOT NULL ,
 FATHER_NAME VARCHAR2 (100 CHAR) NOT NULL ,
 GENDER VARCHAR2 (30) NOT NULL ,
 BATCH INTEGER NOT NULL ,
 EMAIL VARCHAR2 (254 CHAR) NOT NULL ,
 DEGREE VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE STUDENT_DETAILS ADD CONSTRAINT STUDENT_DETAILS_PK PRIMARY KEY ( STUDENT_ID ) ;

-- ----------------------------------------------------------------------------
-- 2. COURSES (Report Page 7)
-- ----------------------------------------------------------------------------
CREATE TABLE COURSES
 (
 COURSE_CODE VARCHAR2 (30) NOT NULL ,
 COURSE_NAME VARCHAR2 (100 CHAR) NOT NULL ,
 CREDIT_HOURS INTEGER NOT NULL ,
 DEPARTMENT_ID VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE COURSES ADD CONSTRAINT COURSES_PK PRIMARY KEY ( COURSE_CODE ) ;

-- ----------------------------------------------------------------------------
-- 3. ATTENDANCE (Report Page 8)
-- ----------------------------------------------------------------------------
CREATE TABLE ATTENDANCE
 (
 STUDENT_ID VARCHAR2 (30) NOT NULL ,
 COURSE_CODE VARCHAR2 (30) NOT NULL ,
 SEMESTER VARCHAR2 (30) NOT NULL ,
 TOTAL_HOURS INTEGER NOT NULL ,
 HOURS_ATTENDED INTEGER NOT NULL ,
 EXAM_STATUS VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE ATTENDANCE ADD CONSTRAINT ATTENDANCE_PK PRIMARY KEY ( STUDENT_ID, COURSE_CODE, SEMESTER ) ;
ALTER TABLE ATTENDANCE ADD CONSTRAINT ATTENDANCE_COURSES_FK FOREIGN KEY ( COURSE_CODE ) REFERENCES COURSES ( COURSE_CODE ) ;
ALTER TABLE ATTENDANCE ADD CONSTRAINT ATTENDANCE_STUDENT_DETAILS_FK FOREIGN KEY ( STUDENT_ID ) REFERENCES STUDENT_DETAILS ( STUDENT_ID ) ;

-- ----------------------------------------------------------------------------
-- 4. ENROLLMENT (Report Page 8)
-- ----------------------------------------------------------------------------
CREATE TABLE ENROLLMENT
 (
 STUDENT_ID VARCHAR2 (30) NOT NULL ,
 COURSE_CODE VARCHAR2 (30) NOT NULL ,
 SEMESTER VARCHAR2 (30) NOT NULL ,
 FACULTY_ID VARCHAR2 (30) NOT NULL ,
 STATUS VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE ENROLLMENT ADD CONSTRAINT ENROLLMENT_PK PRIMARY KEY ( STUDENT_ID, COURSE_CODE, SEMESTER ) ;
ALTER TABLE ENROLLMENT ADD CONSTRAINT ENROLLMENT_COURSES_FK FOREIGN KEY ( COURSE_CODE ) REFERENCES COURSES ( COURSE_CODE ) ;
ALTER TABLE ENROLLMENT ADD CONSTRAINT ENROLLMENT_STUDENT_DETAILS_FK FOREIGN KEY ( STUDENT_ID ) REFERENCES STUDENT_DETAILS ( STUDENT_ID ) ;

-- ----------------------------------------------------------------------------
-- 5. DEPARTMENTS (Report Page 9)
-- ----------------------------------------------------------------------------
CREATE TABLE DEPARTMENTS
 (
 DEPARTMENT_ID VARCHAR2 (30) NOT NULL ,
 DEPARTMENT_NAME VARCHAR2 (100 CHAR) NOT NULL ,
 HOD_ID VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE DEPARTMENTS ADD CONSTRAINT DEPARTMENTS_PK PRIMARY KEY ( DEPARTMENT_ID ) ;
CREATE UNIQUE INDEX DEPARTMENTS__IDX ON DEPARTMENTS ( HOD_ID ASC ) ;

-- ----------------------------------------------------------------------------
-- 6. GRADES (Report Page 9)
-- ----------------------------------------------------------------------------
CREATE TABLE GRADES
 (
 STUDENT_ID VARCHAR2 (30) NOT NULL ,
 COURSE_CODE VARCHAR2 (30) NOT NULL ,
 SEMESTER VARCHAR2 (30) NOT NULL ,
 SESSIONALS INTEGER NOT NULL ,
 FINAL_EXAM INTEGER NOT NULL ,
 GRADE VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE GRADES ADD CONSTRAINT GRADES_PK PRIMARY KEY ( STUDENT_ID, COURSE_CODE, SEMESTER ) ;
ALTER TABLE GRADES ADD CONSTRAINT GRADES_COURSES_FK FOREIGN KEY ( COURSE_CODE ) REFERENCES COURSES ( COURSE_CODE ) ;
ALTER TABLE GRADES ADD CONSTRAINT GRADES_STUDENT_DETAILS_FK FOREIGN KEY ( STUDENT_ID ) REFERENCES STUDENT_DETAILS ( STUDENT_ID ) ;

-- ----------------------------------------------------------------------------
-- 7. DEGREE_PROGRAM (Report Page 10)
-- ----------------------------------------------------------------------------
CREATE TABLE DEGREE_PROGRAM
 (
 DEGREE_ID VARCHAR2 (30) NOT NULL ,
 DEGREE_NAME VARCHAR2 (100 CHAR) NOT NULL ,
 DEPARTMENT_ID VARCHAR2 (30) NOT NULL
 ) ;

ALTER TABLE DEGREE_PROGRAM ADD CONSTRAINT DEGREE_PROGRAM_PK PRIMARY KEY ( DEGREE_ID ) ;
ALTER TABLE DEGREE_PROGRAM ADD CONSTRAINT DEGREE_PROGRAM_DEPARTMENTS_FK FOREIGN KEY ( DEPARTMENT_ID ) REFERENCES DEPARTMENTS ( DEPARTMENT_ID ) ;

-- ----------------------------------------------------------------------------
-- 8. FACULTY (Report Page 10)
-- ----------------------------------------------------------------------------
CREATE TABLE FACULTY
 (
 FACULTY_ID VARCHAR2 (30) NOT NULL ,
 FACULTY_NAME VARCHAR2 (100 CHAR) NOT NULL ,
 GENDER VARCHAR2 (30) NOT NULL ,
 ROLE VARCHAR2 (50 CHAR) NOT NULL ,
 DEPARTMENT_ID VARCHAR2 (30) NOT NULL ,
 EMAIL VARCHAR2 (254 CHAR) NOT NULL
 ) ;

ALTER TABLE FACULTY ADD CONSTRAINT FACULTY_PK PRIMARY KEY ( FACULTY_ID ) ;
ALTER TABLE FACULTY ADD CONSTRAINT FACULTY_DEPARTMENTS_FK FOREIGN KEY ( DEPARTMENT_ID ) REFERENCES DEPARTMENTS ( DEPARTMENT_ID ) ;

-- ----------------------------------------------------------------------------
-- Foreign Key Constraints linking referenced parent tables
-- ----------------------------------------------------------------------------
-- Note: Oracle identifier max length is 30 characters in older Oracle versions
ALTER TABLE STUDENT_DETAILS ADD CONSTRAINT STUDENT_DETAILS_DEGREE_FK FOREIGN KEY ( DEGREE ) REFERENCES DEGREE_PROGRAM ( DEGREE_ID ) ;
ALTER TABLE COURSES ADD CONSTRAINT COURSES_DEPARTMENTS_FK FOREIGN KEY ( DEPARTMENT_ID ) REFERENCES DEPARTMENTS ( DEPARTMENT_ID ) ;
ALTER TABLE ENROLLMENT ADD CONSTRAINT ENROLLMENT_FACULTY_FK FOREIGN KEY ( FACULTY_ID ) REFERENCES FACULTY ( FACULTY_ID ) ;
ALTER TABLE ATTENDANCE ADD CONSTRAINT ATTENDANCE_ENROLLMENT_FK FOREIGN KEY ( STUDENT_ID, COURSE_CODE, SEMESTER ) REFERENCES ENROLLMENT ( STUDENT_ID, COURSE_CODE, SEMESTER ) ;
ALTER TABLE GRADES ADD CONSTRAINT GRADES_ENROLLMENT_FK FOREIGN KEY ( STUDENT_ID, COURSE_CODE, SEMESTER ) REFERENCES ENROLLMENT ( STUDENT_ID, COURSE_CODE, SEMESTER ) ;
ALTER TABLE DEPARTMENTS ADD CONSTRAINT DEPARTMENTS_FACULTY_FK FOREIGN KEY ( HOD_ID ) REFERENCES FACULTY ( FACULTY_ID ) ;
